import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = fileURLToPath(new URL('../', import.meta.url))
const approvedLicenses = new Set(['MIT', 'ISC', 'BSD-3-Clause', 'PSF'])
const supplementalLicenses = {
  '@pixi/colord@2.9.6': {
    file: 'licenses/pixi-colord-2.9.6.txt',
    source: 'https://github.com/pixijs/colord/blob/v2.9.6/LICENSE.md',
  },
}
const readmeLicenses = new Set(['heap@0.2.5', 'pathfinding@0.4.18'])

const readText = async file => (await readFile(file, 'utf8')).replace(/\r\n/g, '\n')
const readJson = async file => JSON.parse(await readText(file))

function declaredLicense(pkg) {
  if (typeof pkg.license === 'string') return pkg.license
  if (pkg.license?.type) return pkg.license.type
  if (pkg.licenses?.length === 1) return pkg.licenses[0].type
  return undefined
}

async function licenseDocuments(root, directory, pkg) {
  const identity = `${pkg.name}@${pkg.version}`
  const names = (await readdir(directory)).filter(name => /^(licen[sc]e|copying|notice)(?:$|[._-])/i.test(name)).sort()
  const documents = await Promise.all(names.map(async name => ({
    source: `${pkg.name}/${name}`,
    text: (await readText(path.join(directory, name))).trim(),
  })))
  if (!documents.length && readmeLicenses.has(identity)) {
    const readme = await readText(path.join(directory, 'README.md'))
    const heading = 'License\n-------\n'
    const offset = readme.indexOf(heading)
    if (offset < 0 || readme.indexOf(heading, offset + heading.length) >= 0) {
      throw new Error(`License section changed: ${identity}; review the upstream license`)
    }
    documents.push({ source: `${pkg.name}/README.md (License section)`, text: readme.slice(offset).trim() })
  }
  if (!documents.length && supplementalLicenses[identity]) {
    const supplement = supplementalLicenses[identity]
    documents.push({ source: supplement.source, text: (await readText(path.join(root, supplement.file))).trim() })
  }
  if (!documents.length || documents.some(document => !document.text)) {
    throw new Error(`Missing license text: ${identity}; add a verified, version-specific license source`)
  }
  return documents
}

export async function collectThirdPartyNotices(root = projectRoot) {
  const lock = await readJson(path.join(root, 'package-lock.json'))
  if (lock.lockfileVersion !== 3 || !lock.packages) throw new Error('A version 3 npm lockfile is required')
  const workspaces = new Set()
  const workspacePatterns = lock.packages['']?.workspaces ?? []
  for (const directory of Object.keys(lock.packages)) {
    if (!workspacePatterns.some(pattern => pattern.endsWith('/*') && directory.startsWith(pattern.slice(0, -1)) && !directory.slice(pattern.length - 1).includes('/'))) continue
    const pkg = await readJson(path.join(root, directory, 'package.json'))
    if (!pkg.name?.startsWith('@pixoffice/') || pkg.version !== lock.packages[directory].version || !pkg.private && pkg.license !== 'MIT') throw new Error(`Unreviewed workspace: ${directory}`)
    workspaces.add(directory)
  }
  const packages = []
  // Include the full production dependency tree, even when tree-shaking omits a module.
  for (const [directory, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    if (!directory || entry.dev) continue
    if (workspaces.has(directory) || entry.link && workspaces.has(entry.resolved)) continue
    if (!directory.startsWith('node_modules/') || entry.link) throw new Error(`Unreviewed dependency location: ${directory}`)
    const installedDirectory = path.join(root, directory)
    const pkg = await readJson(path.join(installedDirectory, 'package.json'))
    if (pkg.version !== entry.version) throw new Error(`Installed version differs from lockfile: ${pkg.name}; run npm ci`)
    const license = declaredLicense(pkg)
    if (!approvedLicenses.has(license)) throw new Error(`Unreviewed license: ${pkg.name}@${pkg.version} (${license ?? 'unknown'})`)
    packages.push({ name: pkg.name, version: pkg.version, license, documents: await licenseDocuments(root, installedDirectory, pkg) })
  }
  const sections = packages.map(pkg => [
    `${pkg.name}@${pkg.version}`,
    `Declared license: ${pkg.license}`,
    ...(pkg.name === 'heap' ? [
      'Change summary: upstream heap.js is a JavaScript/CoffeeScript port of Python heapq.',
      'PixOffice uses the installed package without source changes; the build bundles/minifies it.',
    ] : []),
    ...pkg.documents.flatMap(document => [`Source: ${document.source}`, '', document.text]),
  ].join('\n'))
  const text = [
    'PixOffice - Third-Party Software Notices',
    '',
    'Generated by npm run licenses:generate from the installed, locked production dependencies.',
    'This inventory conservatively includes dependencies that may be removed by tree-shaking.',
    'Each component retains its own license; the PixOffice MIT license does not replace it.',
    'Artwork and other non-code assets are not covered by this software license inventory.',
    '',
    ...sections.flatMap(section => ['='.repeat(78), '', section, '']),
  ].join('\n')
  return { packages, text }
}

export async function generateThirdPartyNotices(root = projectRoot, { check = false } = {}) {
  const { packages, text } = await collectThirdPartyNotices(root)
  const outputs = new Map([
    ['public/THIRD_PARTY_NOTICES.txt', text],
    ['public/LICENSE.txt', await readText(path.join(root, 'LICENSE'))],
  ])
  for (const [name, content] of outputs) {
    const file = path.join(root, name)
    let existing
    try { existing = await readText(file) } catch (error) { if (error.code !== 'ENOENT') throw error }
    if (existing === content) continue
    if (check) throw new Error(`Outdated license notice: ${name}; run npm run licenses:generate`)
    await writeFile(file, content)
  }
  return packages.length
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  try {
    const count = await generateThirdPartyNotices(projectRoot, { check })
    console.log(`Third-party notices ${check ? 'verified' : 'generated'}: ${count} production packages`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
